#!/usr/bin/env bash
#
# run-memory-check.sh - run the full vorbis encode/decode test suite under
# memory checking tools and fail on any leak or out-of-bounds access.
#
# Checks performed:
#   1. AddressSanitizer + UndefinedBehaviorSanitizer + LeakSanitizer build of
#      the repository's own CMake test entry points (test/vorbis_test and
#      test/test_codebook).  LSan is enabled, so any leak aborts the run.
#   2. A plain (non-instrumented) build re-run under valgrind memcheck, when a
#      valgrind deployment is available, as an independent cross-check.
#
# The test material is generated by the tests themselves (a small windowed
# sine), so no external assets are required.
#
# Usage:  scripts/run-memory-check.sh
# Result: exits non-zero on the first finding; prints a summary at the end.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=toolchain.sh
source "$HERE/toolchain.sh"

BUILD_ASAN="$REPO_ROOT/build-memcheck-asan"
BUILD_PLAIN="$REPO_ROOT/build-memcheck-plain"

SANITIZER_FLAGS="-fsanitize=address,undefined -fno-omit-frame-pointer -fno-sanitize-recover=all -g -O1"

export ASAN_OPTIONS="detect_leaks=1:halt_on_error=1:abort_on_error=0${ASAN_OPTIONS:+:$ASAN_OPTIONS}"
export UBSAN_OPTIONS="print_stacktrace=1:halt_on_error=1${UBSAN_OPTIONS:+:$UBSAN_OPTIONS}"

section() { printf '\n==== %s ====\n' "$*"; }

# Every test run is teed into one log and then asserted to contain no
# sanitizer diagnostics, so a single run both demonstrates and verifies.
sanitizer_log="$(mktemp)"
trap 'rm -f "$sanitizer_log"' EXIT

assert_clean() {
  if grep -Eqi 'AddressSanitizer|LeakSanitizer|UndefinedBehaviorSanitizer|runtime error|ERROR: |SUMMARY: ' "$sanitizer_log"; then
    cat "$sanitizer_log"
    echo "memory-check: sanitizer finding detected" >&2
    exit 1
  fi
}

# --- 1. ASan + UBSan + LSan -------------------------------------------------
section "Configuring sanitizer build"
cmake -S "$REPO_ROOT" -B "$BUILD_ASAN" -DCMAKE_BUILD_TYPE=Debug \
  -DCMAKE_C_FLAGS="$SANITIZER_FLAGS" \
  -DCMAKE_EXE_LINKER_FLAGS="$SANITIZER_FLAGS" \
  -DOGG_INCLUDE_DIR="$OGG_INCLUDE_DIR" -DOGG_LIBRARY="$OGG_LIBRARY"

section "Building with AddressSanitizer/UBSan"
cmake --build "$BUILD_ASAN" -j"$(nproc)"

section "Running test_codebook under ASan/UBSan/LSan"
"$BUILD_ASAN/test/test_codebook" 2>&1 | tee "$sanitizer_log"
assert_clean

section "Running full encode/decode suite (528 cases) under ASan/UBSan/LSan"
"$BUILD_ASAN/test/vorbis_test" 2>&1 | tee "$sanitizer_log"
assert_clean

# --- 2. valgrind memcheck cross-check --------------------------------------
if [[ "$HAVE_VALGRIND" -eq 1 ]]; then
  section "Configuring plain build for valgrind"
  cmake -S "$REPO_ROOT" -B "$BUILD_PLAIN" -DCMAKE_BUILD_TYPE=Debug \
    -DOGG_INCLUDE_DIR="$OGG_INCLUDE_DIR" -DOGG_LIBRARY="$OGG_LIBRARY"
  cmake --build "$BUILD_PLAIN" -j"$(nproc)"

  section "Running test_codebook under valgrind memcheck"
  valgrind_run "$BUILD_PLAIN/test/test_codebook"

  section "Running full encode/decode suite under valgrind memcheck"
  valgrind_run "$BUILD_PLAIN/test/vorbis_test"
else
  section "valgrind unavailable; ASan/UBSan/LSan results stand alone"
fi

section "MEMORY CHECK RESULT: PASS (no leaks, no out-of-bounds, no UB)"
